export const RUNTIME_MANIFESTS: readonly RuntimeAdapterManifest[] = manifests.map((manifest) =>
  RuntimeAdapterManifestSchema.parse(manifest),
);

export const getRuntimeManifest = (
  runtime: RuntimeAdapterManifest["runtime"],
): RuntimeAdapterManifest => {
  const manifest = RUNTIME_MANIFESTS.find((candidate) => candidate.runtime === runtime);
  if (!manifest) {
    throw new Error(`Runtime manifest is missing for ${runtime}`);
  }

  return manifest;
};
